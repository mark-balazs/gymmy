/**
 * German.
 *
 * Four things the strings below depend on:
 *   - Informal throughout: 'du'/'dein', never 'Sie'. A coach who knows you.
 *   - Real plural forms exist, so 'plural.*.one' and '.other' differ:
 *     '1 Satz' / '3 Sätze', '1 Einheit' / '3 Einheiten'.
 *   - Movement and split names are substituted at runtime and have mixed
 *     gender (die Kniebeuge, das Tragen, der Ausfallschritt), so no sentence
 *     around {name} or {split} may carry an article: 'diese Woche fehlt {name}',
 *     'Was ist {split}?' — never 'kein {name}' or 'der {split}'.
 *   - 'von' takes the dative, so counted nouns are in the dative plural:
 *     '{done} von {n} Sätzen', not '… Sätze'.
 *
 * 'Einheit' means a training session; the unit setting is 'Maßeinheit' so the
 * two never read as the same word.
 */

