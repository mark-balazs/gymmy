/**
 * Spanish.
 *
 * Rules the strings below depend on:
 *   - Questions and exclamations open with ¿ / ¡, closing mark included.
 *   - Informal "tú" everywhere, never "usted": imperatives are the tú form
 *     ('elige', 'guarda', 'cúbrelos'), and possessives are 'tu'.
 *   - {name} and {list} are movement names of mixed gender ('la sentadilla',
 *     'el acarreo'), so the sentences around them carry no article or agreeing
 *     adjective: 'Falta un movimiento: … no hubo {name}', never 'Falta {name}'.
 *   - Nothing is said about the user's own gender either — 'Ya puedes subir
 *     peso', not 'Listo para más peso' — because the app never asks for it
 *     outside the strength curve.
 *   - Plurals: Intl.PluralRules picks 'one' only for exactly 1, so the two
 *     forms genuinely differ ('1 serie' / '3 series').
 *
 * Vocabulary fixed across the file: a split is 'rutina', a slot in a day is a
 * 'hueco', and a missing movement is something that 'falta' — so the two never
 * collide in the week screen.
 */

