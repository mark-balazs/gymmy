/**
 * French.
 *
 * Rules the strings below depend on:
 *   - A narrow no-break space precedes ? ! : and ; — written here as an ordinary
 *     space, since the app does no typesetting of its own.
 *   - French counts 0 and 1 alike, so 'plural.*.one' covers both: '0 série',
 *     '1 série', '2 séries'.
 *   - Informal 'tu' throughout, and 'ton/ta' rather than 'votre'.
 *   - Elision ('de' → 'd’' before a vowel) cannot be done at runtime, so no
 *     placeholder holding an exercise or movement name sits after 'de' — hence
 *     '{name}, c’est quoi ?' and 'Un manque cette semaine : {name}.' rather than
 *     'À propos de {name}'. Only {split}, whose values are all fixed and
 *     consonant-initial, is allowed to follow one.
 *   - '{pct} %' keeps the space French puts before the percent sign.
 */

